SET NAMES utf8mb4;
-- Полная схема базы «Киосквода» и стартовые данные для чистой установки.
-- Не импортировать повторно поверх более свежей рабочей базы без резервной копии.
CREATE TABLE IF NOT EXISTS kiosks (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 machine_number INT UNSIGNED NULL,
 address VARCHAR(255) NOT NULL,
 area VARCHAR(100) NOT NULL,
 latitude DECIMAL(9,6) NOT NULL,
 longitude DECIMAL(9,6) NOT NULL,
 status ENUM('active','maintenance','planned','hidden') NOT NULL DEFAULT 'active',
 schedule VARCHAR(100) NOT NULL DEFAULT 'Круглосуточно',
 metro VARCHAR(100) NOT NULL DEFAULT '',
 landmark VARCHAR(150) NOT NULL DEFAULT '',
 photo_url VARCHAR(255) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 UNIQUE KEY uq_machine_number (machine_number),
 KEY idx_status_area (status, area)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS kiosk_audit (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 kiosk_id INT UNSIGNED NULL,
 action VARCHAR(40) NOT NULL,
 admin_name VARCHAR(100) NOT NULL,
 ip_hash CHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 KEY idx_kiosk_created (kiosk_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Полный снимок карточки после каждого изменения нужен для истории и точного отката.
CREATE TABLE IF NOT EXISTS kiosk_versions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 kiosk_id INT UNSIGNED NOT NULL,
 action VARCHAR(30) NOT NULL,
 snapshot_json JSON NOT NULL,
 admin_name VARCHAR(100) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (id),
 KEY idx_version_kiosk_created (kiosk_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

